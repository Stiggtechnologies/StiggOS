/**
 * Seed the Northview Residential REIT seasonal contract end-to-end.
 *
 * Idempotent — safe to re-run. Every upsert is keyed by a stable identifier
 * (client.account_number, site.name, contract.contract_number, etc.).
 *
 * Loads:
 *   • Client                              Northview Residential REIT
 *   • 7 sites                             Parkview I/II, 6/4 Nixon, 16/15 Saunderson, MacDonald
 *   • Contract                            NV-2026-0001 with seasonal pricing
 *   • contract_sites links                Marks MacDonald as is_optional
 *   • Tour routes A/B + 6 checkpoints     Each site
 *   • Post orders                         Markdown body per site
 *   • Arming schedule                     "Northview after-hours patrol"
 *   • Linkage rule                        Notify on missed-tour at any Northview site
 *   • Dawn Collier portal user
 *   • 60 days of shifts                   Generated by @stigg/scheduling
 *
 * Usage:
 *   SUPABASE_URL=... SUPABASE_SERVICE_ROLE_KEY=... \
 *     npm run seed:northview -- --org=<org_uuid> [--dawn-password=<temp>] [--days=60]
 */

