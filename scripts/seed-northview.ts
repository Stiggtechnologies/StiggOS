// ─── Helpers ────────────────────────────────────────────────────────────────

async function upsertOnce<T extends Record<string, any>>(
  table: string, match: Record<string, any>, payload: Record<string, any>,
): Promise<T> {
  let q = sb.from(table).select('*');
  for (const [k, v] of Object.entries(match)) q = q.eq(k, v as any);
  const { data: existing } = await q.maybeSingle();
  if (existing) {
    const { data, error } = await sb.from(table).update(payload).eq('id', existing.id).select('*').single();
    if (error) throw error;
    return data as T;
  }
  const { data, error } = await sb.from(table).insert({ ...match, ...payload }).select('*').single();
  if (error) throw error;
  return data as T;
}

async function ensure<T extends Record<string, any>>(
  table: string, match: Record<string, any>, payload: Record<string, any>,
): Promise<T> { return upsertOnce<T>(table, match, payload); }

const wkt = (lng: number, lat: number) => `POINT(${lng} ${lat})`;

// ─── Main ───────────────────────────────────────────────────────────────────

async function main() {
  console.log('▶ Seeding Northview seasonal contract into org', orgId);

  // 1) Client.
  const client = await ensure<{ id: string }>('clients',
    { org_id: orgId, account_number: 'NV-NORTHVIEW' },
    {
      name: 'Northview Residential REIT',
      legal_name: 'Northview Canadian High Yield Residential Fund',
      industry: 'real_estate',
      tier: 'Premium',
      status: 'active',
      service_lines: ['guarding'],
      portal_enabled: true,
      primary_contact: { name: 'Dawn Collier', title: 'Regional Manager', email: dawnEmail },
      tags: ['residential', 'fort-mcmurray', 'reit'],
    },
  );
  console.log(`✓ client ${client.id}`);

  // 2) Sites + post orders + tour routes + checkpoints.
  const siteIdByName = new Map<string, string>();
  for (const spec of SITES) {
    const site = await ensure<{ id: string }>(
      'sites',
      { org_id: orgId, name: spec.name, client_id: client.id },
      {
        address: { street: spec.address, city: spec.city, province: spec.region, postal: spec.postal },
        city: spec.city, region: spec.region, postal_code: spec.postal,
        geo: wkt(spec.lng, spec.lat),
        geofence_radius_m: 120,
        site_type: 'residential',
        remote: false,
        hazards: [],
        service_lines: ['guarding'],
        is_active: true,
        post_order_template: POST_ORDER_TEMPLATE(spec),
        metadata: { suites: spec.suites, optional: spec.optional },
      },
    );
    siteIdByName.set(spec.name, site.id);

    // Post-order row (versioned).
    const { data: existingPost } = await sb.from('post_orders').select('id').eq('site_id', site.id).eq('is_current', true).maybeSingle();
    if (!existingPost) {
      await sb.from('post_orders').insert({
        org_id: orgId, site_id: site.id, version: 1,
        body_md: POST_ORDER_TEMPLATE(spec),
        is_current: true,
      });
    }

    // Two tour routes per site (A and B).
    for (const flow of ['A', 'B'] as const) {
      const route = await ensure<{ id: string }>(
        'tour_routes',
        { org_id: orgId, site_id: site.id, name: `Route ${flow}` },
        { expected_duration_min: 25, is_active: true },
      );
      // Idempotent checkpoints.
      for (const cp of CHECKPOINTS) {
        const tokenSeed = `${site.id}:${flow}:${cp.ordinal}`;
        await upsertOnce('tour_checkpoints',
          { org_id: orgId, route_id: route.id, ordinal: cp.ordinal },
          { label: cp.label, scan_method: cp.scan_method, scan_token: tokenSeed },
        );
      }
    }
  }
  console.log(`✓ ${SITES.length} sites + post orders + ${SITES.length * 2} routes + ${SITES.length * 2 * CHECKPOINTS.length} checkpoints`);

  // 3) Arming schedule — Northview after-hours patrol windows.
  const arming = await ensure<{ id: string }>(
    'arming_schedules',
    { org_id: orgId, name: 'Northview after-hours patrol' },
    {
      spec: {
        timezone: 'America/Edmonton',
        windows: [
          { days: [1,2,3,4,5,6,7], start: '19:30', end: '23:30' },   // Wave 1
          { days: [1,2,3,4,5,6,7], start: '00:30', end: '03:30' },   // Wave 2 (winter)
        ],
      },
      is_active: true,
    },
  );

  // 4) Linkage rule: missed tour at any Northview site → notify management.
  // Org-wide listener on `tour_miss` events; uses the arming window so we
  // don't auto-notify outside the patrol window.
  await upsertOnce('linkage_rules',
    { org_id: orgId, scope_type: 'org', priority: 50 },
    {
      event_types: ['tour_miss'],
      arming_schedule_id: arming.id,
      actions: [{ kind: 'notify_email', params: { to: dawnEmail, subject: 'Northview — patrol miss notification' } }],
      is_active: true,
    },
  );

  // 5) Contract.
  const today = new Date().toISOString().slice(0, 10);
  const contract = await ensure<{ id: string }>(
    'contracts',
    { org_id: orgId, contract_number: 'NV-2026-0001' },
    {
      client_id: client.id,
      service_lines: ['guarding'],
      start_date: today,
      end_date: null,
      monthly_value_cad: 14150,                                     // peak winter rate
      bill_terms: 'Monthly in arrears, GST 5% extra, net 30. Month-to-month with 30 days written notice.',
      pricing_schedule: SEASONAL_PRICING,
      kpi_targets: KPI_TARGETS,
      status: 'active',
      signed_at: new Date().toISOString(),
    },
  );

  // 6) contract_sites links.
  for (const [name, site_id] of siteIdByName.entries()) {
    const spec = SITES.find((s) => s.name === name)!;
    await upsertOnce('contract_sites',
      { contract_id: contract.id, site_id },
      { org_id: orgId, is_optional: spec.optional, added_at: today },
    );
  }
  console.log(`✓ contract ${contract.id} with seasonal pricing`);

  // 7) Dawn Collier — client portal user.
  if (dawnPassword) {
    const { data: existing } = await sb.auth.admin.listUsers();
    const existingUser = existing.users.find((u) => u.email?.toLowerCase() === dawnEmail.toLowerCase());
    let authUserId: string;
    if (existingUser) {
      authUserId = existingUser.id;
      await sb.auth.admin.updateUserById(authUserId, { password: dawnPassword });
    } else {
      const { data, error } = await sb.auth.admin.createUser({ email: dawnEmail, password: dawnPassword, email_confirm: true });
      if (error) throw error;
      authUserId = data.user.id;
    }
    await upsertOnce('user_profiles',
      { auth_user_id: authUserId, org_id: orgId },
      { email: dawnEmail, full_name: 'Dawn Collier', role: 'client', client_id: client.id, is_active: true },
    );
    console.log(`✓ portal user ${dawnEmail} (role=client, scoped to Northview)`);
  } else {
    console.log(`↺ skipping Dawn Collier auth user — pass --dawn-password=<temp> to provision`);
  }

  // 8) Generate and insert the next ${days} days of shifts.
  const sites: ScheduleSite[] = SITES.map((s) => ({
    site_id: siteIdByName.get(s.name)!,
    is_optional: s.optional,
  }));
  const cfg: SeasonalConfig = {
    summer_months: [5,6,7,8,9,10],
    winter_months: [11,12,1,2,3,4],
    summer_visits_per_night: 1,
    winter_visits_per_night: 2,
    wave_1_start: '19:30',
    wave_1_end:   '23:30',
    wave_2_start: '00:30',
    wave_2_end:   '03:30',
    visit_duration_min: 25,
    flows: [
      { id: 'A', site_order: SITES.map((s) => siteIdByName.get(s.name)!) },
      { id: 'B', site_order: [
        siteIdByName.get('Parkview I Apartments')!,
        siteIdByName.get('6 Nixon')!,
        siteIdByName.get('16 Saunderson')!,
        siteIdByName.get('Parkview II Apartments')!,
        siteIdByName.get('4 Nixon')!,
        siteIdByName.get('15 Saunderson')!,
        siteIdByName.get('MacDonald Place')!,
      ]},
    ],
    timezone: 'America/Edmonton',
    bill_rate_cad_hr: 39.40,
    pay_rate_cad_hr:  19.50,
    summer_optional_pattern: 'every_other_day',
  };

  const start = new Date();
  const end = new Date(start.getTime() + days * 86_400_000);
  const startISO = start.toISOString().slice(0, 10);
  const endISO = end.toISOString().slice(0, 10);
  const shifts = generateSchedule({
    config: cfg, sites,
    start_date: startISO,
    end_date: endISO,
    seed: `${contract.id}:${startISO}`,
  });

  // 8a) Insert demand rows (guard_id NULL — the Schedule Agent assigns later).
  // Idempotency: we never insert a duplicate (site_id, scheduled_start) tuple.
  let inserted = 0, skipped = 0;
  for (const s of shifts) {
    const { data: existing } = await sb.from('shifts').select('id')
      .eq('org_id', orgId).eq('site_id', s.site_id).eq('scheduled_start', s.scheduled_start)
      .maybeSingle();
    if (existing) { skipped++; continue; }
    const { error } = await sb.from('shifts').insert({
      org_id: orgId, site_id: s.site_id, guard_id: null,
      scheduled_start: s.scheduled_start, scheduled_end: s.scheduled_end,
      shift_type: s.shift_type, status: 'scheduled',
      bill_rate: s.bill_rate ?? null, pay_rate: s.pay_rate ?? null,
      generated_by_ai: true,
      notes: `Northview ${s.flow} · wave ${s.wave}`,
    });
    if (error) {
      console.warn(`  ! shift insert failed at ${s.scheduled_start}: ${error.message}`);
    } else {
      inserted++;
    }
  }
  console.log(`✓ shifts: ${inserted} inserted, ${skipped} already present (${shifts.length} total demand rows)`);

  console.log('\n▶ Northview seed complete.');
  console.log('   Contract: NV-2026-0001');
  console.log(`   Client portal login: ${dawnEmail}${dawnPassword ? '' : ' (set --dawn-password to provision)'}`);
  console.log(`   Shifts seeded: ${days} days starting ${startISO}`);
  console.log('   Next steps:');
  console.log('     • Open Console → Contracts → NV-2026-0001 to see KPI dashboard');
  console.log('     • Open Console → Cameras to add NVRs if any');
  console.log('     • Open Console → Scheduling → Generate to assign guards to demand');
}

main().catch((e) => { console.error(e); process.exit(1); });
